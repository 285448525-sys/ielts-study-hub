LIST.forEach((f, i) => {
  const port = 9300 + i;
  // _with_server.cjs 按 process.cwd() 解析脚本路径，这里 cwd 是仓库根，所以要带上 tests/ 前缀
  const r = spawnSync(process.execPath, [withServer, path.join('tests', f), String(port)], {
    cwd: '..', encoding: 'utf8', timeout: 300000, maxBuffer: 20 * 1024 * 1024
  });
  // ⚠️ 各支探针的汇总行写法并不统一：有的是「===== N 通过 / M 失败 =====」，
  //    有的是「结果: N/M」，还有的（_probe_chain / _probe_timeline）压根不打通过数 ——
  //    它们只打性能/时间线数据。这类探针的成功判据改成「退出码 0 且没有 ✗ / Error」，
  //    不看通过数；有 ✗ 或非零退出才算这支有问题。
  const out = (r.stdout || '') + (r.stderr || '');
  let m = out.match(/=====\s*(\d+)\s*通过\s*\/\s*(\d+)\s*失败\s*=====/);
  let p, q;
  if (m) { p = Number(m[1]); q = Number(m[2]); }
  else if ((m = out.match(/结果[:：]\s*(\d+)\s*\/\s*(\d+)/))) { p = Number(m[1]); q = Number(m[2]) - Number(m[1]); }
  else {
    p = (out.match(/✓/g) || []).length;
    q = (out.match(/✗/g) || []).length;
    if (!m && !q && r.status === 0 && out.length > 200) { p = p || 1; }  // 数据型探针：跑通即算过
  }
  if (!q && r.status !== 0) { q = 1; }  // 没打 ✗ 但退出码非零 → 记 1 个失败，别静默放过
  if (q === 0 && p > 0) { pass++; console.log('✓ ' + f + '  ' + p + ' 通过'); }
  else {
    fail++; bad.push(f);
    console.log('✗ ' + f + '  ' + p + ' 通过 / ' + q + ' 失败');
    out.split('\n').filter(l => /✗|Error|error:/.test(l)).slice(0, 6).forEach(l => console.log('     ' + l.trim()));
    if (r.error) console.log('     error: ' + r.error.message);
  if (!m) console.log('     （本支没打汇总行）' + (out.match(/结果[:：]\s*\d+\s*\/\s*\d+/) ? '' : ' 也找不到「结果: N/M」，仅按 ✓/✗ 判定'));
  }
});
console.log('\n===== 回归汇总：' + pass + ' 支全绿 / ' + fail + ' 支有问题 =====');
if (bad.length) console.log('有问题：' + bad.join(', '));
process.exit(fail ? 1 : 0);
